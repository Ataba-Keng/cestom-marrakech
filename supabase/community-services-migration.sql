-- Section Talents & services de la communauté CESTOM.
-- À exécuter dans Supabase > SQL Editor pour une base déjà existante.

create table if not exists public.community_services (
  id bigint generated by default as identity primary key,
  name varchar(160) not null,
  business_name varchar(180) not null default '',
  category varchar(120) not null,
  description text not null,
  image_url text not null default '',
  phone varchar(40) not null default '',
  whatsapp boolean not null default false,
  facebook_url text not null default '',
  instagram_url text not null default '',
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists community_services_category_idx on public.community_services(category);
alter table public.community_services enable row level security;

drop policy if exists "Public can read active community services" on public.community_services;
create policy "Public can read active community services" on public.community_services
  for select to anon, authenticated using (active = true);

drop policy if exists "Admins can manage community services" on public.community_services;
create policy "Admins can manage community services" on public.community_services
  for all to authenticated
  using (exists (select 1 from public.admin_users a where (a.user_id = auth.uid() or lower(a.email) = lower(auth.jwt() ->> 'email')) and a.active))
  with check (exists (select 1 from public.admin_users a where (a.user_id = auth.uid() or lower(a.email) = lower(auth.jwt() ->> 'email')) and a.active));
